:- use_module(library(lists)).

% solution(-Solution)
% Declarative reading: Solution is a list of four terms p(Name, Dept, Lang, Project)
% for 'Alex', 'Ben', 'Carla', and 'Dana' in order, where each attribute domain
% (Dept, Lang, Project) is a permutation of its four distinct values.
solution([
    p('Alex', D1, L1, P1),
    p('Ben',  D2, L2, P2),
    p('Carla', D3, L3, P3),
    p('Dana', D4, L4, P4)
]) :-
    permutation([research, development, design, testing], [D1, D2, D3, D4]),
    permutation([python, java, 'c++', javascript], [L1, L2, L3, L4]),
    permutation(['AI', web, embedded, data], [P1, P2, P3, P4]).

% clue(+ClueNum, +Solution)
% Declarative reading: Holds iff ClueNum is 1..9 and clue ClueNum is satisfied by Solution.
clue(1, Sol) :-
    member(p(_, Dept, _, 'AI'), Sol),
    Dept \= research,
    \+ member(p('Dana', _, _, 'AI'), Sol).

clue(2, Sol) :-
    member(p('Alex', Dept, Lang, _), Sol),
    Dept \= development,
    Lang \= 'c++'.

clue(3, Sol) :-
    member(p(_, testing, python, _), Sol).

clue(4, Sol) :-
    member(p('Ben', Dept, _, web), Sol),
    Dept \= testing.

clue(5, Sol) :-
    member(p(_, design, java, _), Sol).

clue(6, Sol) :-
    member(p('Carla', Dept, _, Project), Sol),
    Project \= embedded,
    Dept \= development.

clue(7, Sol) :-
    member(p('Dana', Dept, Lang, _), Sol),
    Lang \= java,
    (Dept == research ; Dept == testing).

clue(8, Sol) :-
    member(p(_, Dept, Lang, data), Sol),
    Dept == research,
    Lang \= javascript.


% CLUE 9: The friend working in the design department prefers embedded projects.
clue(9, Sol) :-
    member(p(_, design, _, embedded), Sol).


% Declarative reading: Finds one valid solution satisfying clues 1..9
% and prints the assignments for Alex, Ben, Carla, and Dana in order.

main :-
    solution(Sol),
    valid_for_clues([1,2,3,4,5,6,7,8,9], Sol),
    !,
    print_solution(Sol).

% valid_for_clues(+ClueNums, +Solution)
% Declarative reading: Holds when every clue number in ClueNums is satisfied by Solution.
valid_for_clues([], _).
valid_for_clues([N | Ns], Sol) :-
    clue(N, Sol),
    valid_for_clues(Ns, Sol).

% print_solution(+Solution)
% Declarative reading: Prints each p(Name, Dept, Lang, Project) in Solution
% on its own line as "<Name> = [<Dept>, <Lang>, <Project>]".
print_solution([]).
print_solution([p(Name, Dept, Lang, Project) | Rest]) :-
    write(Name),
    write(' = ['),
    write(Dept),
    write(', '),
    write(Lang),
    write(', '),
    write(Project),
    write(']'),
    nl,
    print_solution(Rest).
    % count_solutions(+Active, -N)
% Declarative reading: N is the count of solutions generated by solution/1
% that satisfy every clue in Active.
count_solutions(Active, N) :-
    aggregate_all(
        count,
        (solution(Sol), valid_for_clues(Active, Sol)),
        N
    ).

